#!/usr/bin/env python3
"""
load_catalog_if_empty.py — Checks if crawl_targets is empty and loads from YAML if so.

Adapted for wb-parser-kotlin:
  - Reads YAML from the project root (wb_catalog_targets.yaml)
  - Calls load_catalog_to_pg.py from the same directory
  - Works with the current schema (wb_catalog_id, wb_parent_catalog_id, TEXT[] allowed_domains)

Usage:
    python load_catalog_if_empty.py --db-name wbparser --db-user postgres --db-password pass
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

import click

# Path to the YAML generated by catalog_selector.py (project root)
CATALOG_YAML = Path(__file__).parent.parent.parent / "wb_catalog_targets.yaml"
LOAD_SCRIPT = Path(__file__).parent / "load_catalog_to_pg.py"


def get_pg_value(
    host: str,
    port: int,
    db: str,
    user: str,
    password: str,
    sql: str,
) -> str | None:
    """Execute a SQL query via psql and return the first value."""
    result = subprocess.run(
        ["psql", "-h", host, "-p", str(port), "-d", db, "-U", user, "-t", "-c", sql],
        env={"PGPASSWORD": password},
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        return None
    return result.stdout.strip()


def is_crawl_targets_empty(
    host: str,
    port: int,
    db: str,
    user: str,
    password: str,
) -> bool:
    """Return True when crawl_targets has zero rows."""
    val = get_pg_value(host, port, db, user, password, "SELECT COUNT(*) FROM crawl_targets;")
    if val is None or val == "":
        return True
    try:
        return int(val) == 0
    except ValueError:
        return True


def run_load_script(
    yaml_path: Path,
    db_host: str,
    db_port: int,
    db_name: str,
    db_user: str,
    db_password: str,
) -> int:
    """Run load_catalog_to_pg.py as a subprocess."""
    cmd = [
        sys.executable,
        str(yaml_path),
        "--db-host", db_host,
        "--db-port", str(db_port),
        "--db-name", db_name,
        "--db-user", db_user,
        "--db-password", db_password,
    ]
    result = subprocess.run(cmd, env={"PGPASSWORD": db_password})
    return result.returncode


@click.command()
@click.option("--db-host", default="localhost")
@click.option("--db-port", default=5432, type=int)
@click.option("--db-name", required=True)
@click.option("--db-user", required=True)
@click.option("--db-password", required=True)
@click.option(
    "--yaml-path",
    type=click.Path(path_type=Path),
    default=None,
    help="Override the default YAML path.",
)
def main(
    db_host: str,
    db_port: int,
    db_name: str,
    db_user: str,
    db_password: str,
    yaml_path: Path | None,
) -> None:
    yaml_path = yaml_path or CATALOG_YAML

    click.echo("Checking if crawl_targets is empty...")
    if not is_crawl_targets_empty(db_host, db_port, db_name, db_user, db_password):
        click.echo("crawl_targets already has data — skipping.")
        return

    if not yaml_path.exists():
        click.echo(f"Catalog YAML not found: {yaml_path}", err=True)
        click.echo("Run catalog_selector.py first to generate the YAML.", err=True)
        raise click.Abort()

    if not LOAD_SCRIPT.exists():
        click.echo(f"load_catalog_to_pg.py not found: {LOAD_SCRIPT}", err=True)
        raise click.Abort()

    click.echo(f"DB is empty — loading catalog from {yaml_path}...")
    rc = run_load_script(
        yaml_path,
        db_host,
        db_port,
        db_name,
        db_user,
        db_password,
    )
    if rc != 0:
        click.echo(f"load_catalog_to_pg.py failed with code {rc}", err=True)
        raise click.Abort()

    click.echo("Catalog loaded successfully.")


if __name__ == "__main__":
    main()
